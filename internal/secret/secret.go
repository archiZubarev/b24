// Пакет secret хранит ссылки вебхуков в хранилище системы: на macOS —
// в Связке ключей, на Windows — в Диспетчере учётных данных. На диск
// открытым текстом ключ не попадает, в аргументы процессов тоже: утилита
// говорит с хранилищем через системные вызовы, а не через security или cmdkey.
package secret

import "errors"

// Service — имя, под которым ключи лежат в хранилище. Тесты меняют его,
// чтобы не задеть настоящие ключи.
var Service = "b24"

// ErrNotFound — в хранилище нет записи с таким именем.
var ErrNotFound = errors.New("в хранилище нет такого ключа")

// ErrUnsupported — на этой системе хранилище не поддерживается.
var ErrUnsupported = errors.New("хранилище ключей есть только на macOS и Windows")
